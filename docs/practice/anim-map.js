/* Анимация «Карта метода». Основа — главы «Инструментальный подход», «Психоэнергетика как инструмент с позиции МКС»,
   «Комплекс базовых упражнений», «Язык состояний» книги «Огненный цветок. Методика ДФС». */
(function (G) {
  'use strict';
  var D = G.DFSC, A = D.A, L = D.L;

  function node(cx, cy, w, h, title, sub, col) {
    return '<g transform="translate(' + (cx - w / 2) + ' ' + (cy - h / 2) + ')">' +
      '<rect width="' + w + '" height="' + h + '" rx="16" fill="rgba(255,255,255,.07)" stroke="' + (col || '#ffd27a') + '" stroke-opacity=".75" stroke-width="2"/>' +
      '<text x="' + (w / 2) + '" y="' + (sub ? h / 2 - 3 : h / 2 + 6) + '" text-anchor="middle" font-size="17" font-weight="700" fill="#fff" font-family="Georgia,serif">' + title + '</text>' +
      (sub ? '<text x="' + (w / 2) + '" y="' + (h / 2 + 17) + '" text-anchor="middle" class="cap2">' + sub + '</text>' : '') + '</g>';
  }
  function link(x1, y1, x2, y2, dash) {
    return '<path d="M' + x1 + ' ' + y1 + ' L' + x2 + ' ' + y2 + '" stroke="rgba(255,255,255,.35)" stroke-width="2" fill="none"' + (dash ? ' stroke-dasharray="5 6"' : '') + '/>';
  }

  A.map = function () {
    var p = 'mp';
    var scene = A.defs(p) +
      /* три инструмента */
      L('tools', node(250, 90, 170, 56, 'Тело', 'движения, ощущения') + node(110, 300, 170, 56, 'Сознание', 'слова, память, мысль') + node(390, 300, 170, 56, 'Психоэнергетика', 'переживания, настроения', '#ffb85a') +
        link(250, 118, 140, 272) + link(250, 118, 360, 272) + link(196, 300, 304, 300)) +
      /* хозяин */
      L('owner', '<g class="pop"><circle cx="250" cy="230" r="46" fill="url(#' + p + 'H)"/><circle cx="250" cy="230" r="31" fill="url(#' + p + 'S)" filter="url(#' + p + 'G)"/>' +
        '<text x="250" y="236" text-anchor="middle" font-size="20" font-weight="800" fill="#3a2400" font-family="Georgia,serif">Я</text></g>' +
        '<text class="cap2" x="250" y="280" text-anchor="middle">самосознание</text>') +
      /* четыре аспекта психоэнергетики */
      L('form', node(390, 392, 170, 52, 'Огненный цветок', 'конструкция, форма', '#ffd27a') + link(390, 328, 390, 366, true)) +
      L('lang', node(250, 470, 190, 52, '16 состояний', 'язык: центр × ритм', '#9fc0ff') + link(390, 418, 300, 448, true)) +
      L('range', node(104, 392, 196, 52, 'Диапазон звучания', 'результат практики', '#b6f0c8') + link(196, 392, 304, 392, true)) +
      L('reson', node(250, 560, 190, 52, 'Резонанс', 'связь с пространством', '#ff9a9a') + link(250, 496, 250, 534, true)) +
      L('four', '<g class="pop"><rect x="150" y="598" width="200" height="40" rx="20" fill="url(#' + p + 'S)" filter="url(#' + p + 'G)"/><text x="250" y="624" text-anchor="middle" font-size="18" font-weight="800" fill="#3a2400" font-family="Georgia,serif">«четвёрка»</text></g>');

    var steps = [
      { t: 'Три инструмента', add: ['tools'],
        d: 'Предложение методики — посмотреть на себя как на хозяина трёх инструментов, данных при рождении: тела, сознания и психоэнергетики. Проверка простая: что вы умеете с их помощью делать?' },
      { t: 'Хозяин — самосознание', add: ['owner'],
        d: 'Нужен тот, кто управляет всеми тремя инструментами: не тело, не сознание и не сама психоэнергетика. Его называют самосознанием («я есмь»).' },
      { t: 'Форма инструмента — «Огненный цветок»', add: ['form'],
        d: 'Чтобы психоэнергетика стала рабочим инструментом, ей нужна устойчивая форма. Это телесно ощущаемая функциональная система «Огненный цветок».' },
      { t: 'Язык состояний', add: ['lang'],
        d: 'Чтобы работать с этим инструментом, нужен язык. 16-значный язык состояний (четыре ритма и четыре уровня) задаёт его качественную определённость.' },
      { t: 'Результат — диапазон звучания', add: ['range'],
        d: 'Продукт работы этого инструмента — диапазон звучания человека: управляемое многообразие психоэнергетических состояний.' },
      { t: 'Связь — резонанс', add: ['reson'],
        d: 'Способность входить в резонанс с окружающим миром, ситуациями и людьми даёт чувство включённости в мир и активной позиции.' },
      { t: 'Цель — «четвёрка»', add: ['four'],
        d: 'По автору, овладение «четвёрками» — идеальная цель занятий на хорошем уровне: нужно выработать привычку находиться в 4B или 4C. Базовые упражнения («Полёт белой птицы», «Созерцание», «Кино», «Ноль-концентрация») работают как единый комплекс.', ms: 12000 }
    ];
    return { id: 'map', svg: A.svg('0 0 500 660', scene, 'sc-mp'), steps: steps, ar: '500/660', label: 'Схема: как устроен метод', maxh: '640px' };
  };
})(window);
